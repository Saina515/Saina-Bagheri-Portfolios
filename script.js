  function markCurrentPage() {
    document.querySelectorAll('.site-nav .nav-link, .footer-nav .footer-link').forEach((link) => {
      const linkKey = getPageKeyFromHref(link.getAttribute('href'));
      const isCurrent = linkKey !== null && linkKey === state.pageKey;

      if (link.classList.contains('nav-link')) {
        link.classList.toggle('is-active', isCurrent);
      }

      if (isCurrent) {
        link.setAttribute('aria-current', 'page');
      } else {
        link.removeAttribute('aria-current');
      }
    });
  }

  function initMobileNavigation() {
    const toggle = document.getElementById('nav-toggle');
    const panel = document.getElementById('nav-panel');

    if (!toggle || !panel) {
      return;
    }

    const header = toggle.closest('.site-header') || document.getElementById('site-header');
    const isOpen = () => toggle.getAttribute('aria-expanded') === 'true';

    const setOpen = (open, restoreFocus = false) => {
      toggle.setAttribute('aria-expanded', String(open));
      if (!open && restoreFocus) {
        toggle.focus();
      }
    };

    toggle.addEventListener('click', () => {
      setOpen(!isOpen());
    });

    /* Choosing a navigation link closes the menu. */
    panel.addEventListener('click', (event) => {
      if (isElement(event.target) && event.target.closest('a[href]')) {
        setOpen(false);
      }
    });

    /* Escape closes the menu and returns focus to the toggle. */
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape' && isOpen()) {
        setOpen(false, true);
      }
    });

    /* Clicking or tabbing outside the header closes the menu. */
    const closeWhenLeavingHeader = (event) => {
      if (!isOpen() || !header || !(event.target instanceof Node)) {
        return;
      }
      if (!header.contains(event.target)) {
        setOpen(false);
      }
    };
    document.addEventListener('click', closeWhenLeavingHeader);
    document.addEventListener('focusin', closeWhenLeavingHeader);

    /* Returning to the desktop layout resets the mobile state. */
    if (window.matchMedia) {
      const desktopQuery = window.matchMedia(CONFIG.desktopNavQuery);
      const handleDesktopChange = (event) => {
        if (event.matches) {
          setOpen(false);
        }
      };
      if (typeof desktopQuery.addEventListener === 'function') {
        desktopQuery.addEventListener('change', handleDesktopChange);
      } else if (typeof desktopQuery.addListener === 'function') {
        desktopQuery.addListener(handleDesktopChange);
      }
    }
  }

  /* ----------------------------------------------------------------------
   * 9. Motion preference (exposed for CSS hooks and future page modules;
   *    the portfolio's motion itself is controlled by style.css)
   * -------------------------------------------------------------------- */

  function initMotionPreference() {
    const root = document.documentElement;

    if (!window.matchMedia) {
      root.setAttribute('data-motion', 'standard');
      return;
    }

    const query = window.matchMedia(CONFIG.motionQuery);
    const updateMotion = () => {
      root.setAttribute('data-motion', query.matches ? 'reduced' : 'standard');
    };

    updateMotion();
    if (typeof query.addEventListener === 'function') {
      query.addEventListener('change', updateMotion);
    } else if (typeof query.addListener === 'function') {
      query.addListener(updateMotion);
    }
  }

  /* ----------------------------------------------------------------------
   * 10. Contact forms
   *     No messaging service is connected in this project, so a form is
   *     never reported as sent. A form only sends when it declares its own
   *     endpoint with data-contact-endpoint.
   * -------------------------------------------------------------------- */

  function getFormStatus(form) {
    let status = form.querySelector('[data-form-status]');

    if (!status) {
      status = document.createElement('p');
      status.className = 'form-note';
      status.setAttribute('data-form-status', '');
      status.setAttribute('role', 'status');
      status.setAttribute('aria-live', 'polite');
      form.appendChild(status);
    }

    return status;
  }

  function handleContactSubmit(event, form) {
    event.preventDefault();
    const status = getFormStatus(form);

    if (typeof form.reportValidity === 'function' && !form.reportValidity()) {
      return;
    }

    const endpoint = form.getAttribute('data-contact-endpoint');

    if (!endpoint || typeof window.fetch !== 'function') {
      status.textContent = translate('form.unavailable');
      return;
    }

    status.textContent = translate('form.sending');
    form.setAttribute('aria-busy', 'true');

    window.fetch(endpoint, {
      method: 'POST',
      body: new FormData(form),
      headers: { Accept: 'application/json' }
    })
      .then((response) => {
        if (!response.ok) {
          throw new Error('Request failed');
        }
        form.reset();
        status.textContent = translate('form.sent');
      })
      .catch(() => {
        status.textContent = translate('form.error');
      })
      .finally(() => {
        form.removeAttribute('aria-busy');
      });
  }

  function initContactForms() {
    document.querySelectorAll('form[data-contact-form]').forEach((form) => {
      form.addEventListener('submit', (event) => {
        handleContactSubmit(event, form);
      });
    });
  }

